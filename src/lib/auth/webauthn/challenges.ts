import { and, eq, gt, inArray, isNull, lt } from "drizzle-orm";
import { getDb } from "@/db";
import { webauthnChallenges } from "@/db/schema";
import { newId } from "@/lib/ids";
import { hashSessionToken } from "@/lib/auth/session";

export const WEBAUTHN_COOKIE = "ep_webauthn";
const CEREMONY_MINUTES = 10;
const MAX_BINDINGS = 6;
const SEPARATOR = "~";

export type WebAuthnPurpose = "login" | "mfa" | "register" | "step_up" | "check" | "enroll" | "recovery";

export type WebAuthnChallenge = {
	id: string;
	challenge: string;
	purpose: WebAuthnPurpose;
	userId: string | null;
	bindingHash: string;
	/** The raw binding that matched, so only that browser ceremony is cleared. */
	binding: string;
	expiresAt: Date;
};

/** A random value kept in an HttpOnly cookie so a ceremony stays in one browser. */
export function createCeremonyBinding(): string {
	return newId("wbn");
}

/**
 * A short list lets sequential ceremonies in different tabs coexist. Truly
 * simultaneous starts can still overwrite each other's cookie; losing a
 * ceremony is harmless and the user can start it again.
 */
export function readCeremonyBindings(request: Request): string[] {
	const cookie = request.headers.get("Cookie") ?? "";
	const match = cookie.match(new RegExp(`(?:^|;\\s*)${WEBAUTHN_COOKIE}=([^;]+)`));
	if (!match) return [];
	try {
		return decodeURIComponent(match[1]).split(SEPARATOR).filter(Boolean).slice(-MAX_BINDINGS);
	} catch {
		return [];
	}
}

export function ceremonyBindingHash(binding: string): Promise<string> {
	return hashSessionToken(binding);
}

function serializeBindings(bindings: string[]): string {
	return encodeURIComponent(Array.from(new Set(bindings)).slice(-MAX_BINDINGS).join(SEPARATOR));
}

/** Adds a binding to the browser cookie without dropping another tab's. */
export function setCeremonyCookie(headers: Headers, binding: string, existing: string[] = []): void {
	const secure = process.env.NODE_ENV === "production";
	headers.append(
		"Set-Cookie",
		`${WEBAUTHN_COOKIE}=${serializeBindings([...existing, binding])}; Path=/; HttpOnly; SameSite=Lax; Max-Age=${CEREMONY_MINUTES * 60}${secure ? "; Secure" : ""}`,
	);
}

/** Removes only the ceremony that just completed. */
export function removeCeremonyCookie(headers: Headers, request: Request, usedBinding: string): void {
	const remaining = readCeremonyBindings(request).filter((binding) => binding !== usedBinding);
	if (remaining.length === 0) {
		clearCeremonyCookie(headers);
		return;
	}
	const secure = process.env.NODE_ENV === "production";
	headers.append(
		"Set-Cookie",
		`${WEBAUTHN_COOKIE}=${serializeBindings(remaining)}; Path=/; HttpOnly; SameSite=Lax; Max-Age=${CEREMONY_MINUTES * 60}${secure ? "; Secure" : ""}`,
	);
}

export function clearCeremonyCookie(headers: Headers): void {
	const secure = process.env.NODE_ENV === "production" ? "; Secure" : "";
	headers.append("Set-Cookie", `${WEBAUTHN_COOKIE}=; Path=/; HttpOnly; SameSite=Lax; Max-Age=0${secure}`);
}

/**
 * Stores the challenge generated by SimpleWebAuthn. Only the ceremony token is
 * a bearer value; it is hashed at rest and paired with a browser binding.
 */
export async function createWebAuthnChallenge(
	env: CloudflareEnv,
	input: {
		challenge: string;
		purpose: WebAuthnPurpose;
		userId?: string | null;
		binding: string;
	},
): Promise<{ ceremonyToken: string; expiresAt: Date }> {
	const db = getDb(env);
	const ceremonyToken = newId("wac");
	const expiresAt = new Date(Date.now() + CEREMONY_MINUTES * 60 * 1000);
	await db.insert(webauthnChallenges).values({
		id: newId(),
		ceremonyHash: await hashSessionToken(ceremonyToken),
		challenge: input.challenge,
		purpose: input.purpose,
		userId: input.userId ?? null,
		bindingHash: await ceremonyBindingHash(input.binding),
		expiresAt,
	});
	// Expired ceremonies are useless; dropping them keeps the table small.
	await db.delete(webauthnChallenges).where(lt(webauthnChallenges.expiresAt, new Date()));
	return { ceremonyToken, expiresAt };
}

/**
 * Atomically burns a ceremony. The conditional update is what stops a replayed
 * token from producing a second session, even under concurrent requests.
 */
export async function consumeWebAuthnChallenge(
	env: CloudflareEnv,
	input: { ceremonyToken: string; purpose: WebAuthnPurpose; bindings: string[] },
): Promise<WebAuthnChallenge | null> {
	if (input.bindings.length === 0) return null;
	const db = getDb(env);
	const hashes = await Promise.all(input.bindings.map(ceremonyBindingHash));
	const [row] = await db
		.select()
		.from(webauthnChallenges)
		.where(
			and(
				eq(webauthnChallenges.ceremonyHash, await hashSessionToken(input.ceremonyToken)),
				eq(webauthnChallenges.purpose, input.purpose),
				inArray(webauthnChallenges.bindingHash, hashes),
				isNull(webauthnChallenges.usedAt),
				gt(webauthnChallenges.expiresAt, new Date()),
			),
		)
		.limit(1);
	if (!row) return null;
	const matchedIndex = hashes.indexOf(row.bindingHash);
	const binding = input.bindings[matchedIndex];
	if (!binding) return null;
	const claimed = await db
		.update(webauthnChallenges)
		.set({ usedAt: new Date() })
		.where(and(eq(webauthnChallenges.id, row.id), isNull(webauthnChallenges.usedAt)))
		.returning({ id: webauthnChallenges.id });
	if (!claimed.length) return null;
	return {
		id: row.id,
		challenge: row.challenge,
		purpose: row.purpose,
		userId: row.userId,
		bindingHash: row.bindingHash,
		binding,
		expiresAt: row.expiresAt,
	};
}
